"""FSV Module — WAF / CDN Detection (passive fingerprint)"""

from __future__ import annotations
from fsv.core.scanner import BaseScanner
from fsv.core.models import Finding, Severity, Confidence


# signature → (header substrings, body substrings, cookie substrings)
WAF_SIGNATURES = {
    "Cloudflare":        (["cf-ray", "cf-cache-status", "server: cloudflare"], ["attention required! | cloudflare"], ["__cfduid", "cf_clearance"]),
    "AWS WAF / CloudFront": (["x-amz-cf-id", "x-amzn-requestid", "server: awselb"], [], []),
    "Akamai":            (["x-akamai", "akamaighost", "server: akamaighost"], [], ["ak_bmsc"]),
    "Imperva Incapsula": (["x-iinfo", "x-cdn: incapsula"], ["incapsula incident"], ["incap_ses", "visid_incap"]),
    "Sucuri":            (["x-sucuri-id", "x-sucuri-cache", "server: sucuri"], ["sucuri website firewall"], []),
    "F5 BIG-IP ASM":     (["x-waf-event", "server: big-ip"], [], ["ts", "bigipserver"]),
    "Barracuda":         (["barra_counter_session"], [], ["barra_counter_session"]),
    "ModSecurity":       (["server: mod_security", "mod_security"], ["mod_security", "not acceptable"], []),
    "Fastly":            (["x-served-by: cache", "x-fastly", "fastly-debug"], [], []),
    "Fortinet FortiWeb": (["fortiwafsid"], [], ["fortiwafsid"]),
    "Wordfence":         (["wordfence"], ["generated by wordfence"], []),
    "Azure Front Door":  (["x-azure-ref", "x-fd-"], [], []),
}


class WAFScanner(BaseScanner):
    name     = "waf_detect"
    category = "passive"
    scope    = "site"

    async def scan(self, url: str) -> list[Finding]:
        status, headers, body = await self.fetch(url)
        if status == -1:
            return []

        hay_headers = " ".join(f"{k}: {v}" for k, v in headers.items()).lower()
        hay_body    = (body or "").lower()[:5000]
        hay_cookies = " ".join(v for k, v in headers.items() if k.lower() == "set-cookie").lower()

        detected: list[str] = []
        for waf, (hsigs, bsigs, csigs) in WAF_SIGNATURES.items():
            if (any(s in hay_headers for s in hsigs)
                    or any(s in hay_body for s in bsigs)
                    or any(s in hay_cookies for s in csigs)):
                detected.append(waf)

        if not detected:
            return [Finding(
                title       = "No WAF / CDN Detected",
                severity    = Severity.INFO,
                url         = url,
                module      = self.name,
                confidence  = Confidence.TENTATIVE,
                description = (
                    "No Web Application Firewall or CDN was fingerprinted from the response. "
                    "The application may be directly exposed without an edge security layer."
                ),
                recommendation = (
                    "Consider placing the application behind a WAF/CDN (Cloudflare, AWS WAF, "
                    "etc.) to filter malicious traffic and absorb DDoS."
                ),
                references  = ["https://owasp.org/www-community/Web_Application_Firewall"],
                extra       = {"waf": []},
            )]

        return [Finding(
            title       = f"WAF / CDN Detected: {', '.join(detected)}",
            severity    = Severity.INFO,
            url         = url,
            module      = self.name,
            confidence  = Confidence.FIRM,
            description = (
                f"The target appears to be protected by: {', '.join(detected)}. "
                "This affects how other findings should be interpreted — some payloads "
                "may be filtered at the edge rather than fixed in the application."
            ),
            evidence    = f"Fingerprinted: {', '.join(detected)}",
            recommendation = (
                "A WAF is defence-in-depth, not a substitute for fixing the underlying "
                "issues. Ensure the application itself is secure even if the WAF is bypassed."
            ),
            references  = ["https://owasp.org/www-community/Web_Application_Firewall"],
            extra       = {"waf": detected},
        )]
