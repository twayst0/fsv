"""FSV — Report generator (Markdown + JSON)"""

from __future__ import annotations
import json
from datetime import datetime
from fsv.core.models import ScanResult, Severity


SEVERITY_EMOJI = {
    Severity.CRITICAL: "🔴",
    Severity.HIGH:     "🟠",
    Severity.MEDIUM:   "🟡",
    Severity.LOW:      "🔵",
    Severity.INFO:     "⚪",
}


def generate_markdown(result: ScanResult) -> str:
    lines: list[str] = []
    a = lines.append

    a("# FSV Security Scan Report")
    a("")
    a(f"**Target:** `{result.target}`")
    a(f"**Scan ID:** `{result.scan_id}`")
    a(f"**Started:** {result.started_at}")
    a(f"**Finished:** {result.finished_at}")
    a(f"**Duration:** {result.duration_s:.1f}s")
    a(f"**URLs Scanned:** {result.urls_scanned}")
    if result.tech_stack:
        a(f"**Tech Stack:** {', '.join(result.tech_stack)}")
    a("")
    a("---")
    a("")

    # Summary table
    a("## Summary")
    a("")
    a("| Severity | Count |")
    a("|----------|-------|")
    a(f"| 🔴 Critical | {result.critical_count} |")
    a(f"| 🟠 High     | {result.high_count} |")
    a(f"| 🟡 Medium   | {result.medium_count} |")
    a(f"| 🔵 Low      | {result.low_count} |")
    a(f"| ⚪ Info     | {result.info_count} |")
    a(f"| **Total**   | **{len(result.findings)}** |")
    a("")

    if not result.findings:
        a("✅ No vulnerabilities detected.")
        return "\n".join(lines)

    a("---")
    a("")
    a("## Findings")
    a("")

    for i, f in enumerate(result.findings, 1):
        emoji = SEVERITY_EMOJI.get(f.severity, "⚪")
        a(f"### {i}. {emoji} {f.title}")
        a("")
        a(f"- **Severity:** {f.severity.value.upper()}")
        a(f"- **Module:** `{f.module}`")
        a(f"- **URL:** `{f.url}`")
        if f.parameter:
            a(f"- **Parameter:** `{f.parameter}`")
        if f.cwe:
            a(f"- **CWE:** [{f.cwe}](https://cwe.mitre.org/data/definitions/{f.cwe.split('-')[-1]}.html)")
        if f.cvss_score is not None:
            a(f"- **CVSS:** {f.cvss_score}")
        a("")
        a(f"**Description:**")
        a(f.description)
        a("")
        if f.evidence:
            a(f"**Evidence:**")
            a(f"```\n{f.evidence[:500]}\n```")
            a("")
        if f.recommendation:
            a(f"**Recommendation:**")
            a(f.recommendation)
            a("")
        if f.references:
            a("**References:**")
            for ref in f.references:
                a(f"- {ref}")
            a("")
        a("---")
        a("")

    a("")
    a("*Report generated by [FSV](https://github.com/fsvproject/fsv) — "
      "for authorized security testing only.*")
    return "\n".join(lines)


def generate_json(result: ScanResult) -> str:
    return json.dumps(
        {
            **result.summary_dict(),
            "findings": [f.model_dump() for f in result.findings],
        },
        indent=2,
        ensure_ascii=False,
    )
